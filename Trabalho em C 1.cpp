#include <stdio.h>
int main() {
// Declara uma variável inteira para guardar a idade
int idade = 20;
// Declara uma variável float para guardar a altura
float altura = 1.75;
// Declara uma variável char para guardar a inicial do nome
char inicial = 'A';
// Exibe a idade na tela
printf("Idade: %d\n", idade);
// Exibe a altura com duas casas decimais
printf("Altura: %.2f\n", altura);
// Exibe a inicial do nome
printf("Inicial do nome: %c\n", inicial);
// Finaliza o programa
return 0;
}
